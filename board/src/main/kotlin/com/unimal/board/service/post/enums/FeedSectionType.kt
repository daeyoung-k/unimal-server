package com.unimal.board.service.post.enums

/**
 * 지도 바텀카드 피드 섹션 종류.
 *
 * 설계: `docs/specs/2026-07-29-지도-바텀카드-피드-api.md` §2 / §10(2026-07-30 개정)
 *
 * **선언 순서가 곧 응답의 표시 순서다.** [MapFeedService] 가 `entries` 순회로
 * 섹션을 배열에 담으므로, 순서를 바꾸려면 여기만 고치면 된다.
 * 지도 앱이므로 "여기 근처"([NEAR])가 맨 위다.
 *
 * 표시 순서와 **배정 순서는 다르다.** 배정은 "못 채웠을 때 보충할 수 없는" 섹션부터 —
 * [NEAR](5km) → [LATEST](48시간) → [ALL](사진 있는 전국 글).
 * 넓은 섹션을 먼저 배정하면 좁은 섹션이 쓸 글을 먼저 가져가 통째로 사라진다.
 * (2026-08-06 개정 — 자세한 근거는 `MapFeedService.buildSections` 주석)
 *
 * 헤더 문구를 서버가 내려주는 이유: 문구를 바꿀 때 앱 스토어 심사를 다시 받지 않아도 된다.
 * 2026-08-06 개정 이후로는 서비스가 문구를 갈아끼우는 경로가 없어, 여기 [title] 이
 * 그대로 응답에 나간다(반경 폴백 제거 — 아래 [NEAR] 주석 참고).
 */
enum class FeedSectionType(val title: String) {
    /**
     * **5km 이내**, 가까운 순. 기간 제한 없음. 텍스트 글도 포함한다.
     *
     * 5km 안에서 최소 건수를 못 채우면 **섹션을 내리지 않는다.** 예전에는 반경을 풀고
     * 헤더만 "가까운 이야기"로 바꿔 내보냈는데, 저밀도 지역(예: 서산)에서 100km 밖 글이
     * "가까운"이라는 이름을 달고 나오는 문제가 있었다. 거리 약속을 못 지킬 바엔
     * 섹션을 안 보여주는 쪽이 정직하다. (2026-08-06)
     *
     * **기간 제한을 뺀 이유(2026-08-06):** 원래 이름이 "지금 여기 이야기"라 48시간
     * 제한이 "지금"과 맞았는데, "가까운 스토리"로 바꾸면서 이름이 거리만 주장하게 됐다.
     * 필터만 남겨두니 447m 짜리 3일 전 글이 [NEAR] 가 아니라 [ALL]("전국 스토리")에
     * 뜨는 일이 생겼다 — 사용자 눈에는 그냥 버그다. 이름이 약속하는 것과 필터를 맞춘다.
     *
     * 기간을 안 걸어도 무한정 늘어나지 않는다. 후보 풀 SQL 이 이미 "사진 없는 글은
     * 48시간"을 걸고 있어, 실질적으로 **"5km 내 사진 글 전부 + 48시간 내 텍스트 글"**이다.
     * 신선도는 [LATEST] 가 담당한다.
     */
    NEAR("가까운 스토리"),

    /**
     * 48시간 이내 글, 최신순. 사진 없는 텍스트 글도 포함한다.
     *
     * [NEAR] 다음에 배정되므로 실질적으로 **"주변에서 이미 본 것 말고 새로 올라온 것"**
     * 이 된다. 5km 밖에서 방금 올라온 글이 주로 여기 앉는다.
     * 반경 제한이 없으므로 헤더도 거리를 주장하지 않는다 — 기준은 어디까지나 시간이다.
     */
    LATEST("방금 올라온 스토리"),

    /**
     * **사진이 있는** 글. 시간감쇠순. 전국 대상, 거리·기간 무제한.
     *
     * 사진을 요구하는 이유: 이 섹션은 "볼 만한 것"을 보여주는 자리라 텍스트 마커가
     * 상단에 오면 캐러셀이 빈 카드처럼 보인다. 시간 제한은 없다 — 사진 있는 글은
     * 48시간 컷 대상이 아니고, [MapFeedService.hotScore] 가 시간감쇠라 묵은 글은
     * 알아서 밀린다.
     *
     * **원래 이름은 `HOT`("지금 인기 있는 스토리")이었다.** 반응 1건이면 통과라
     * "인기"라고 부를 만한 표본이 아직 안 된다(2026-08-06 기준 사용자 수).
     * 인기 컨셉을 접고 "전국 글"로 성격을 바꾸면서 이름도 [ALL] 로 옮겼다.
     *
     * **반응(좋아요·댓글) ≥ 1 조건은 2026-08-06 에 제거했다.** 이름을 바꾸며 인기
     * 컨셉을 접었는데 조건만 관성으로 남아 있었고, 반응이 거의 없는 현재 데이터에서
     * 최소 건수를 못 채워 피드가 통째로 비는 원인이 됐다. **이 섹션은 반응을
     * 약속하지 않는다** — 사진만 있으면 볼 만한 글이다.
     *
     * 데이터가 쌓여 진짜 인기 섹션을 만들 때는 **이 값을 재활용하지 말고 `HOT` 을
     * 새로 추가할 것.** 정렬식이 같다고 같은 섹션이 아니다 — 사용자에게 하는 약속이
     * 다르다("볼 만한 것" vs "진짜 인기").
     */
    ALL("전국 스토리"),
}
