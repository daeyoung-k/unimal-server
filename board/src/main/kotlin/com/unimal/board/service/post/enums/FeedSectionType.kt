package com.unimal.board.service.post.enums

/**
 * 지도 바텀카드 피드 섹션 종류.
 *
 * 설계: `docs/specs/2026-07-29-지도-바텀카드-피드-api.md` §2 / §10(2026-07-30 개정)
 *
 * **선언 순서가 곧 응답의 표시 순서다.** [MapFeedService] 가 `entries` 순회로
 * 섹션을 배열에 담으므로, 순서를 바꾸려면 여기만 고치면 된다.
 *
 * 표시 순서와 **배정 순서는 다르다.** 배정은 희소한 섹션부터 —
 * [HOT](반응 있는 글만) → [LATEST](최근 N일) → [NEAR](나머지 전부).
 * 희소한 섹션을 뒤로 미루면 앞 섹션이 풀을 다 먹어서 뒤 섹션이 최소 건수를
 * 못 채우고 통째로 사라진다.
 *
 * 헤더 문구를 서버가 내려주는 이유: 문구를 바꿀 때 앱 스토어 심사를 다시 받지 않아도 된다.
 */
enum class FeedSectionType(val title: String) {
    /** 최근 [MapFeedService] `LATEST_WINDOW_DAYS` 이내, 최신순. */
    LATEST("방금 올라온 소식"),

    /** 반응(좋아요·댓글)이 1개 이상인 글만, 시간감쇠 인기순. */
    HOT("지금 인기 있는 스토리"),

    /** 현재 위치에서 가까운 순. 반경 제한 없음 — 밀도가 낮아도 피드가 비지 않는다. */
    NEAR("지금 여기 이야기"),
}
