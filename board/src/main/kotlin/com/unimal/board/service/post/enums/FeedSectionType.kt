package com.unimal.board.service.post.enums

/**
 * 지도 바텀카드 피드 섹션 종류.
 *
 * 설계: `docs/specs/2026-07-29-지도-바텀카드-피드-api.md` §2 / §10(2026-07-30 개정)
 *
 * **선언 순서가 곧 응답의 표시 순서다.** [MapFeedService] 가 `entries` 순회로
 * 섹션을 배열에 담으므로, 순서를 바꾸려면 여기만 고치면 된다.
 *
 * 표시 순서와 **배정 순서는 다르다.** 배정은 좁은 섹션부터 —
 * [HOT](사진 + 반응) → [NEAR](5km + 48시간) → [LATEST](48시간).
 * 넓은 섹션을 먼저 배정하면 좁은 섹션이 쓸 글을 먼저 가져가 통째로 사라진다.
 * (2026-07-31 개정 — 자세한 근거는 `MapFeedService.buildSections` 주석)
 *
 * 헤더 문구를 서버가 내려주는 이유: 문구를 바꿀 때 앱 스토어 심사를 다시 받지 않아도 된다.
 * [NEAR] 는 5km 안이 비어 반경 폴백이 걸리면 서비스가 문구를 갈아끼우므로,
 * 여기 [title] 이 응답에 그대로 나간다는 보장은 없다.
 */
enum class FeedSectionType(val title: String) {
    /**
     * 48시간 이내 글, 최신순. 사진 없는 텍스트 글도 포함한다.
     *
     * [NEAR] 다음에 배정되므로 실질적으로 **"주변에서 이미 본 것 말고 새로 올라온 것"**
     * 이 된다. 5km 밖에서 방금 올라온 글이 주로 여기 앉는다.
     */
    LATEST("방금 올라온 소식"),

    /**
     * **사진이 있는** 글 중 반응(좋아요·댓글) 1개 이상, 시간감쇠 인기순.
     *
     * 사진을 요구하는 이유: 이 섹션은 "볼 만한 것"을 보여주는 자리라 텍스트 마커가
     * 상단에 오면 캐러셀이 빈 카드처럼 보인다. 시간 제한은 없다 — 사진 있는 글은
     * 48시간 컷 대상이 아니고, `hotScore` 가 시간감쇠라 묵은 글은 알아서 밀린다.
     */
    HOT("지금 인기 있는 스토리"),

    /**
     * **5km 이내** + 48시간 이내, 가까운 순. 텍스트 글도 포함한다.
     *
     * 5km 안에서 최소 건수를 못 채우면 반경 제한을 풀어 폴백하고, 그때는 헤더 문구가
     * `MapFeedService.NEAR_FALLBACK_TITLE` 로 바뀐다 — "지금 여기"라고 해놓고 30km 밖
     * 글을 보여주면 거짓말이 되기 때문이다.
     */
    NEAR("지금 여기 이야기"),
}
