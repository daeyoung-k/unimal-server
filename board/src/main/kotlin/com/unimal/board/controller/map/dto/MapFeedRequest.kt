package com.unimal.board.controller.map.dto

/**
 * 지도 바텀카드 피드 조회 요청.
 *
 * 설계: `docs/specs/2026-07-29-지도-바텀카드-피드-api.md` §3
 *
 * 마커 조회([LocationPostRequest])와 달리 **반경을 쓰지 않는다.** 거리는 필터가 아니라
 * 정렬 기준이다 (PostGIS KNN). 그래서 `siDo`/`guGun`/`dong` 도 받지 않는다.
 */
data class MapFeedRequest(
    val latitude: Double,
    val longitude: Double,

    /**
     * **현재 미사용.** 쿼리에 전달하지 않으므로 값을 바꿔도 응답이 변하지 않는다.
     *
     * 밀도가 올라 `NEAR` 섹션에 반경 캡을 씌우게 될 때를 대비해 앱이 v1 부터 보내게 해둔다.
     * 그때 서버만 배포하면 되고 앱 재배포가 필요 없다.
     */
    val zoom: Int? = null,

    /**
     * 사용자가 새로고침 버튼을 눌러서 온 요청인지 (2026-07-31).
     *
     * true 면 **응답 캐시 읽기를 건너뛴다.** 캐시 TTL 이 60초인데 좌표를 소수점 3자리로
     * 스냅해 키를 만들기 때문에, 같은 자리에서 새로고침을 누르면 60초 동안 직전과
     * 똑같은 JSON 이 돌아온다 — 아이콘만 돌고 목록은 그대로라 사용자에게는 버튼이
     * 고장난 것으로 보인다. 수동 새로고침의 존재 이유를 캐시가 무력화하는 셈이다.
     *
     * **쓰기는 건너뛰지 않는다.** 새로 계산한 결과를 캐시에 덮어써야 뒤따르는 자동
     * 갱신(30초 신선도 타이머)이 다시 캐시를 타고, 갱신 직후의 자동 조회가 옛 응답으로
     * 되돌아가는 일이 없다.
     *
     * 남용 방지는 앱에서 한다 (연타 가드 + 최소 간격). 서버에 레이트리밋을 두지 않는
     * 이유는 이 API 가 비로그인 허용이라 식별자가 IP 뿐이고, 지금 트래픽에서 IP 기준
     * 제한은 같은 와이파이의 여러 사용자를 함께 막는 부작용이 더 크기 때문이다.
     */
    val refresh: Boolean = false,
)
